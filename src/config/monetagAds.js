/**
 * Get configured Monetag ad unit for a given ad number (1-based index)
 * Rotates evenly across all 13 official units
 */
export function getMonetagAdForNumber(adNumber) {
  const index = (Math.max(1, Number(adNumber) || 1) - 1) % MONETAG_ADS.length;
  return MONETAG_ADS[index];
}

/**
 * Safely executes or injects the ad script for an ad unit into the document
 */
export function triggerAdScript(adConfig) {
  if (!adConfig || typeof document === 'undefined') return null;

  try {
    if (adConfig.type === 'script' || adConfig.type === 'vignette_script') {
      const scriptId = `monetag-script-${adConfig.unitNumber}-${adConfig.zone || Date.now()}`;
      
      // Remove any existing script instance to allow re-trigger
      const existing = document.getElementById(scriptId);
      if (existing) {
        existing.remove();
      }

      const script = document.createElement('script');
      script.id = scriptId;
      script.src = adConfig.scriptSrc;
      if (adConfig.zone) {
        script.dataset.zone = adConfig.zone;
        script.setAttribute('data-zone', adConfig.zone);
      }
      script.async = true;
      script.setAttribute('data-cfasync', 'false');

      const target = document.body || document.documentElement;
      target.appendChild(script);
      return script;
    }
  } catch (err) {
    console.warn('Error injecting ad script:', err);
  }
  return null;
}
